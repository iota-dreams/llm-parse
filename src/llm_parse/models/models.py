from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Annotated, Any, Dict, List, Optional, Tuple, Union

from pydantic import BaseModel, Field, field_validator

from .validators import parse_loose_dict


# models/response.py
class TableHandler(str, Enum):
    markdown = "markdown"
    html = "html"


class ImageRepresentation(BaseModel):
    """
    A unified representation of a cropped image in a parsing response.
    """

    # e.g., "image_1"
    key: str
    path: Optional[str] = None
    base64: Optional[str] = None
    format: Optional[str] = "png"
    # width, height
    size: Optional[Tuple[int, int]] = None
    caption: Optional[str] = None


class LLMConfig(BaseModel):
    """
    Configuration for the LLM model.
    """

    provider: str  # "anthropi", "google_gemini", "google_genai", "openai"  Refer this: https://python.langchain.com/docs/integrations/chat/
    model_name: str
    temperature: Optional[float] = 0.7
    prompt: str  # Base system or task prompt
    image_path: Optional[Union[str, Path]] = None
    table_type: Optional[str] = "html"
    safety_settings: Optional[List[Dict[str, Any]]] = None


class ImageDescription(BaseModel):
    description: str
    vlm_confidence: Optional[float] = Field(
        None,
        description="Confidence score (0 to 1) representing certainty of the image"
        "description result.",
    )


class LLMParse(BaseModel):
    """
    Structured response format for document parsing.

    - `text_content`: Extracted text with placeholders like {table_1}, {image_1}.
    - `tables`: Mapping of placeholders to table content in HTML or Markdown.
    - `image_bbox`: Mapping of placeholders to image bounding boxes.
    - `parse_confidence`: Confidence score from 0 to 1.

    This structure enables clean rendering, post-processing, and semantic indexing.
    """

    text_content: str = Field(
        ...,
        description="Main parsed text with placeholders like {table_1}, {image_2}"
        "in place of visual content.",
    )
    image_bbox: Optional[Dict[str, list[float]]] = Field(
        default_factory=dict,
        description="Dictionary mapping image placeholders (e.g., 'image_1') to "
        "bounding box coordinates: [x_min, y_min, x_max, y_max].",
    )
    tables: Optional[Dict[str, str]] = Field(
        default_factory=dict,
        description="Dictionary mapping table placeholders (e.g., 'table_1') to table "
        "content as {{table_format}} (HTML or Markdown).",
    )
    parse_confidence: Optional[float] = Field(
        None,
        description="Confidence score (0 to 1) representing certainty of this parsing"
        "result.",
    )

    @field_validator("tables", mode="before")
    @classmethod
    def validate_tables(cls, value):
        # Allow null-like values from LLMs such as None, "null", or empty string
        # These are normalized into an empty dictionary to prevent validation failure
        if value in (None, "null", ""):
            return {}

        # Attempt to parse JSON or Python-style stringified dicts using utility
        return parse_loose_dict(value, field_name="tables")

    @field_validator("image_bbox", mode="before")
    @classmethod
    def validate_images(cls, value):
        # Same null/empty defensive guard for image_bbox
        if value in (None, "null", ""):
            return {}

        # Use robust parsing for stringified or malformed dicts
        return parse_loose_dict(value, field_name="image_bbox")


class ImageParseData(BaseModel):
    """
    Container for image-related data extracted or generated during LLM parsing.

    This includes:
    - Bounding box guidance for cropped images (used to map placeholders like 'image_1')
    - Optional descriptions generated via vision-language models (VLMs)
    - The LLM config used to generate those descriptions

    This model helps organize image-specific metadata separately within the
    larger `LLMParseResult`, avoiding clutter and improving modularity.
    """

    bbox_guide: Optional[Dict[str, list[float]]] = Field(
        default=None,
        description="Optional guidance for image bounding boxes. "
        "Each key (e.g., 'image_1') maps to [x_min, y_min, x_max, y_max].",
    )

    crops: Optional[List[ImageRepresentation]] = None
    """
    Structured representations for each cropped image region.
    Typically includes base64 or file path, size, format, etc.
    """

    descriptions: Optional[Dict[str, ImageDescription]] = Field(
        default=None,
        description="Optional mapping from image placeholders (e.g., 'image_1') "
        "to structured descriptions generated by an LLM-VLM.",
    )

    description_config: Optional[LLMConfig] = Field(
        default=None,
        description="Configuration used to generate image descriptions, "
        "if applicable.",
    )


class LLMParseResult(BaseModel):
    """
    Encapsulates the full result of a document parsing run using an LLM.

    This includes:
    - The structured parsed content (`LLMParse`)
    - Metadata about the file and page processed
    - Optional guidance for image regions and hyperlinks
    - Timing, token usage, and success status
    """

    parser_config: LLMConfig = Field(
        ...,
        description="Configuration used for the LLM parsing request.",
    )

    parse: LLMParse = Field(
        ...,
        description="Structured parsing result including text, tables, and image"
        "references.",
    )

    file_name: str = Field(
        ...,
        description="Name of the input file from which this content was parsed.",
    )

    page_number: int = Field(
        ...,
        description="1-based index of the page parsed in the source document.",
    )

    total_pages: Annotated[int, Field(ge=1)] = Field(
        default=1,
        description="Total number of pages in the input document.",
    )

    image_data: Optional[ImageParseData] = Field(
        default=None,
        description="Optional metadata about cropped image regions, descriptions, "
        "and associated LLM configuration.",
    )

    hyperlink_guide: Optional[List[str]] = Field(
        default=None,
        description="List of hyperlinks extracted from the page using PyMuPDF "
        "or associated with the parsed content.",
    )

    page_dimensions: Optional[Tuple[float, float]] = Field(
        default=None,
        description="Dimensions of the rendered image representation of the page "
        "as (width, height) in points or pixels.",
    )

    pdf_page_dimensions: Optional[Tuple[float, float]] = Field(
        default=None,
        description="Dimensions of the original PDF page (before rasterization) "
        "as (width, height) in points or pixels.",
    )

    tokens_used: Optional[int] = Field(
        default=None,
        description="Total number of LLM tokens consumed during parsing.",
    )

    latency_ms: Optional[float] = Field(
        default=None,
        description="Total time taken (in milliseconds) to process this parse.",
    )

    success: bool = Field(
        default=True,
        description="Indicates whether the parsing operation was successful.",
    )

    error_message: Optional[str] = Field(
        default=None,
        description="Error message if parsing failed. Only present when `success` is"
        "False.",
    )

    timestamp: datetime = Field(
        default_factory=datetime.utcnow,
        description="UTC timestamp when the parsing result was generated.",
    )


class ImageMetadata(BaseModel):
    base64: str = Field(
        ...,
        description="Base64-encoded string of the image content. Empty if not "
        "available.",
    )
    description: str = Field(
        ...,
        description="Optional human-readable description of the image "
        "(e.g., from a VLM).",
    )


class LLMParseDocumentResponse(BaseModel):
    file_name: Optional[str] = Field(
        None, description="Original filename of the parsed PDF document."
    )
    llm_config: Optional["LLMConfig"] = Field(
        None,
        description="Configuration used by the LLM for parsing this document.",
    )
    text_content: str = Field(
        ...,
        description="Combined markdown text content from all pages, with inlined "
        "tables and image references.",
    )
    images: Dict[str, ImageMetadata] = Field(
        default_factory=dict,
        description=(
            "Dictionary of image metadata keyed by reference path or fallback key. "
            "Each entry contains base64 content and an optional description."
        ),
    )
    skipped_pages: List[int] = Field(
        default_factory=list,
        description="List of page numbers that failed during LLM parsing.",
    )
    errors: Dict[int, str] = Field(
        default_factory=dict,
        description="Mapping from skipped page numbers to error messages.",
    )
    token_count: int = Field(
        ...,
        description="Total number of tokens used across all processed pages.",
    )
    timestamp: str = Field(
        ..., description="UTC timestamp when the final response was generated."
    )
    start_page: int = Field(
        ...,
        description="First page number included in the processed document range.",
    )
    end_page: Optional[int] = Field(
        None,
        description="Last page number included in the processed document range, if "
        "specified.",
    )
